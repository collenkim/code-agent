import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { afterEach, beforeEach, test } from "node:test";
import { start } from "../agent/commands";
import { recordDeliveredCycle } from "../agent/cycles";
import { loadActive, type ActiveWork } from "../agent/layout";
import { confirmStartNotice, requestBegin } from "../agent/request";
import { textHash } from "../agent/requirementRevisions";
import { confirmForTest } from "./confirmedStart";
import { createStageRepo, git, removeStageRepo, repo, write } from "./stageFixture";
const spec = "doc/work/ORD-1/requirement.md";
beforeEach(() => createStageRepo("ca-cycle-start-"));
afterEach(() => removeStageRepo());
test("병합된 작업 시작·접수 안내와 사람의 브랜치 삭제 후 새 회차·보관 정리", () => {
  git("switch", "-qc", "feature/ORD-1");
  write(spec, readFileSync(join(repo, "doc/work/ORD-1.md"), "utf8"));
  const active: ActiveWork = { id: "ORD-1", spec, target: "order", phase: "deliver", branch: "feature/ORD-1" };
  recordDeliveredCycle(repo, active, { requestHash: textHash(readFileSync(join(repo, spec), "utf8")), baseCommit: git("rev-parse", "HEAD"), treeHash: "fixture" });
  git("add", "-f", "--", spec, ".code-agent/work/ORD-1/cycles.json"); git("commit", "-qm", "[ORD-1] 반영");
  const previous = git("rev-parse", "HEAD");
  git("update-ref", "refs/code-agent/archive/ORD-1/1", previous);
  git("switch", "master"); git("merge", "--squash", "feature/ORD-1"); git("commit", "-qm", "squash merge");
  write(spec, readFileSync(join(repo, spec), "utf8").replace("title: 주문 도메인 추가", "title: 추가 보완"));
  confirmForTest(repo, join(repo, spec));
  assert.throws(() => start(repo, join(repo, spec)), /병합된 기록[\s\S]*브랜치는 바꾸지 않았습니다/);
  assert.equal(git("branch", "--show-current"), "master"); assert.equal(loadActive(repo), undefined);
  assert.match(requestBegin(repo, "ORD-1", "feature"), /시작 전 정리 필요:[\s\S]*병합된 기록/);
  assert.match(confirmStartNotice(repo, { id: "ORD-1", kind: "feature", base: "master" } as Parameters<typeof confirmStartNotice>[1], spec), /확정만 남고 시작은 막힙니다/);
  git("branch", "-D", "feature/ORD-1");
  const out = start(repo, join(repo, spec));
  assert.match(out, /실행 회차 2/); assert.match(out, /보관 ref 1개를 정리/);
  assert.equal(loadActive(repo)?.baseCommit, git("rev-parse", "master"));
  assert.equal(git("for-each-ref", "--format=%(refname)", "refs/code-agent/archive/"), "");
});
